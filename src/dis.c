const char *dis_reftype(uint8_t type)
{
  switch (type) {
    case 0x70: return "funcref";
    case 0x6F: return "externref";
    default:
      break;
  }
  fprintf(stderr, "reftype: %02X\n", type);
  assert(false);
}

const char *dis_valtype(uint8_t type)
{
  switch(type) {
    case 0x7F: return "i32";
    case 0x7E: return "i64";
    case 0x7D: return "f32";
    case 0x7C: return "f64";
    case 0x7B: return "v128";
    case 0x70: return "(func)";
    case 0x6F: return "(extern)";
    default:
      break;
  }
  fprintf(stderr, "valtype: %02X\n", type);
  assert(false);
}

const char *dis_exportdesc(uint8_t type)
{
  switch(type) {
    case 0x00: return "func";
    case 0x01: return "table";
    case 0x02: return "memory";
    case 0x03: return "global";
    default:
      break;
  }
  fprintf(stderr, "exportdesc: %02X\n", type);
  assert(false);
}

const char *dis_locals(locals_t *locals, size_t localslen, char *buf, size_t buflen)
{
  size_t i = 0;
  size_t j = 0;
  size_t k = 0;
  k += snprintf(&buf[k], buflen - k, "(local");
  for (i=0; i<localslen; i++) {
    for (j=0; j<locals[i].n; j++) {
      k += snprintf(&buf[k], buflen - k, " %s", dis_valtype(locals[i].t));
    }
  }
  k += snprintf(&buf[k], buflen - k, ")");
  return buf;
}


void dis_expr(const uint8_t *start_buf, size_t len, bool is_newline)
{
  int               nest     = 1;
  int               pre_nest = 0;
  op_t              op       = OP_INVALID;
  const uint8_t    *bufptr   = start_buf;
  const uint8_t   **buf      = &bufptr;
  char              s[64]    = { 0 };
  struct op_param_st param   = { 0 };
  op = instr_next(buf, &param);
  bufptr = start_buf;
  while (nest > 0) {
    op       = instr_next(buf, &param);
    nest     = compute_nest_pre(op, nest);
    pre_nest = nest;
    dis_instr(op, &param, s, sizeof(s));
    nest = compute_nest_post(op, nest);
    if (op == OOP_END && nest == 0) {
      printf(")");
    } else {
      if (is_newline) {
        if (op == OP_BLOCK) {
          printf("\n  %*s", 2 * pre_nest, " ");
	} else {
          printf("\n  %*s", 2 * nest, " ");
	}
      }
      printf("%s", s);
    }
  }
}
