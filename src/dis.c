int compute_nest_pre(op_t op, int nest)
{
  switch (op) {
    case OOP_END:
      return nest - 1;
    default:
      break;
  }
  return nest;
}

int compute_nest_post(op_t op, int nest)
{
  switch (op) {
    case OP_BLOCK:
    case OP_LOOP:
    case OP_IF:
      return nest + 1;
    default:
      break;
  }
  return nest;
}

