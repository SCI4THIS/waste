struct op_memarg_st {
  uint32_t a; /* align */
  uint32_t o; /* offset */
};

struct op_u32_u32_st {
  uint32_t u32_1;
  uint32_t u32_2;
};

struct op_bytes_st {
  uint32_t       len;
  const uint8_t *buf;
};

typedef enum {
  BLOCKTYPE_EPSILON,
  BLOCKTYPE_VALTYPE,
  BLOCKTYPE_X,
} blocktype_t;

struct op_blocktype_st {
  blocktype_t type;
  union {
    uint32_t t; /* valtype */
    uint32_t x; /* s33 */
  } u;
};


typedef struct op_param_st {
  union {
    struct op_memarg_st    memarg;
    struct op_u32_u32_st   u32u32;
    struct op_bytes_st     bytes;
    struct op_blocktype_st block;
    uint32_t               u32;
    int32_t                i32;
    int64_t                i64;
    float                  f32;
    double                 f64;
  } u;
} op_param_t;

